#!/usr/bin/env python3
# gen-timing.py - z80em86 の T ステート表 (emu/src/timing.asm) を生成する
# usage: scripts/gen-timing.py > emu/src/timing.asm
#
# 値は Zilog Z80 CPU User Manual (UM0080) の命令タイミング。
# 表 TCn は命令振り分け表 Tn と同じ並び (opcode 順、1 要素 1 word)。
# 接頭辞付き命令は、接頭辞の 4T を TC0 側で数えるので、表には「全体 - 4」を入れる。
# 条件分岐が成立したときの追加分 (JR cc +5 など) は各ルーチンで数える。

# ---- 接頭辞なし (T0) ----
T0 = [0] * 256
base = [  # 00-3F
    4, 10, 7, 6, 4, 4, 7, 4,   4, 11, 7, 6, 4, 4, 7, 4,
    8, 10, 7, 6, 4, 4, 7, 4,  12, 11, 7, 6, 4, 4, 7, 4,
    7, 10, 16, 6, 4, 4, 7, 4,  7, 11, 16, 6, 4, 4, 7, 4,
    7, 10, 13, 6, 11, 11, 10, 4,  7, 11, 13, 6, 4, 4, 7, 4,
]
T0[0:64] = base
for o in range(0x40, 0x80):            # LD r,r' / (HL)
    T0[o] = 7 if (o & 7) == 6 or ((o >> 3) & 7) == 6 else 4
T0[0x76] = 4                           # HALT
for o in range(0x80, 0xC0):            # ALU A,r / (HL)
    T0[o] = 7 if (o & 7) == 6 else 4
hi = [  # C0-FF
    5, 10, 10, 10, 10, 11, 7, 11,  5, 10, 10, 4, 10, 17, 7, 11,
    5, 10, 10, 11, 10, 11, 7, 11,  5, 4, 10, 11, 10, 4, 7, 11,
    5, 10, 10, 19, 10, 11, 7, 11,  5, 4, 10, 4, 10, 4, 7, 11,
    5, 10, 10, 4, 10, 11, 7, 11,  5, 6, 10, 4, 10, 4, 7, 11,
]
T0[0xC0:] = hi

# ---- CB (T1) ----
T1 = [0] * 256
for o in range(256):
    hl = (o & 7) == 6
    if 0x40 <= o < 0x80:               # BIT
        tot = 12 if hl else 8
    else:                              # rotate/shift, RES, SET
        tot = 15 if hl else 8
    T1[o] = tot - 4

# ---- ED (T2) ----
T2 = [8 - 4] * 256                     # undefined ED xx: 8T NOP
for o in range(0x40, 0x80):
    col = o & 7
    tot = {0: 12, 1: 12, 2: 15, 3: 20, 4: 8, 5: 14, 6: 8}.get(col)
    if col == 7:
        tot = {0x47: 9, 0x4F: 9, 0x57: 9, 0x5F: 9, 0x67: 18, 0x6F: 18}.get(o, 8)
    T2[o] = tot - 4
for o in (0xA0, 0xA1, 0xA2, 0xA3, 0xA8, 0xA9, 0xAA, 0xAB,
          0xB0, 0xB1, 0xB2, 0xB3, 0xB8, 0xB9, 0xBA, 0xBB):
    T2[o] = 16 - 4                     # 1 回分。繰り返しの 21T はルーチン側

# ---- DD / FD (T4 = IX, T3 = IY) ----
TX = [T0[o] for o in range(256)]       # 接頭辞を無視して実行される命令: T0 と同じ
for o in (0x09, 0x19, 0x29, 0x39):
    TX[o] = 15 - 4                     # ADD IX,rr
TX[0x21] = 14 - 4                      # LD IX,nn
TX[0x22] = 20 - 4                      # LD (nn),IX
TX[0x2A] = 20 - 4                      # LD IX,(nn)
TX[0x23] = TX[0x2B] = 10 - 4           # INC/DEC IX
for o in (0x24, 0x25, 0x2C, 0x2D):
    TX[o] = 8 - 4                      # INC/DEC IXH/IXL
TX[0x26] = TX[0x2E] = 11 - 4           # LD IXH/IXL,n
TX[0x34] = TX[0x35] = 23 - 4           # INC/DEC (IX+d)
TX[0x36] = 19 - 4                      # LD (IX+d),n
for o in range(0x40, 0xC0):
    if o == 0x76:
        continue
    src, dst = o & 7, (o >> 3) & 7
    if o < 0x80:
        if src == 6 or dst == 6:
            TX[o] = 19 - 4             # LD r,(IX+d) / LD (IX+d),r
        elif src in (4, 5) or dst in (4, 5):
            TX[o] = 8 - 4              # LD on IXH/IXL
    else:
        if src == 6:
            TX[o] = 19 - 4             # ALU (IX+d)
        elif src in (4, 5):
            TX[o] = 8 - 4              # ALU IXH/IXL
TX[0xCB] = 12                          # DD CB d: CB の M1 + d + アドレス計算
TX[0xE1] = 14 - 4                      # POP IX
TX[0xE3] = 23 - 4                      # EX (SP),IX
TX[0xE5] = 15 - 4                      # PUSH IX
TX[0xE9] = 8 - 4                       # JP (IX)
TX[0xF9] = 10 - 4                      # LD SP,IX

# ---- DD CB d xx / FD CB d xx (T6 = IX, T5 = IY) ----
# 全体 23T (BIT は 20T) = DD 4 + TX[CB] 12 + 下の値
TXCB = [4 if 0x40 <= o < 0x80 else 7 for o in range(256)]


def table(name, vals):
    out = [f'{name}:']
    for r in range(0, 256, 16):
        out.append('        dw      ' + ','.join(f'{v:2d}' for v in vals[r:r + 16]))
    return '\n'.join(out)


print('''; timing.asm - Z80 T-state tables (generated by scripts/gen-timing.py)
; z80em86-88 - 5 October 2026. Values from the Zilog Z80 CPU User Manual (UM0080).
; TCn has the same layout as the opcode table Tn. For prefixed opcodes the
; prefix (4T) is counted in TC0, so TCn holds "total - 4".
; This file is part of z80em86-88 and is distributed under the GPL v2.

SEGMENT	.code	public align=16

GLOBAL  TC0, TC1, TC2, TC3, TC4, TC5, TC6
''')
for name, vals in (('TC0', T0), ('TC1', T1), ('TC2', T2), ('TC3', TX),
                   ('TC4', TX), ('TC5', TXCB), ('TC6', TXCB)):
    print(table(name, vals))
    print()
